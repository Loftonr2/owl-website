Race and Identity

Ages 2ΓÇô4

Children notice race ΓÇö and research from Harvard''s implicit bias laboratory confirms that they notice it much earlier than most parents believe (as early as 6 months for visual preference and 3 years for explicit categorization). Pretending otherwise ("I don''t see color") does not protect children. It leaves them without adult guidance for something their brains are already processing.

Do say: "Yes, people have different skin colors and that''s beautiful. Your skin is [color]. Larissa has [color] skin. Your friend Maya has [color] skin."
Don''t say: "We don''t see color in this family." This communicates that difference is uncomfortable and should not be discussed.

Ages 5ΓÇô8

Children at this age will encounter racial bias ΓÇö either directed at them or witnessed. They need language to process both.

Do say: "What that person said/did was not okay. It''s called racism and it happens because some people haven''t learned that all people deserve to be treated with respect. You did not do anything wrong."

Key principle: Children who receive clear, honest explanations of racism ΓÇö at age-appropriate levels ΓÇö are better equipped to navigate it than children who are told everything is fine.

Trauma, Fear, and News Events

All Ages: The Regulation Conversation Before the Explanation

Before any difficult conversation about a scary or traumatic event, check in with your own emotional state. Children are exquisitely sensitive co-regulators ΓÇö if you are panicked while delivering information, the information will be experienced as terrifying regardless of the words you choose. Take a breath first.

Ages 2ΓÇô5

Children this age cannot process abstract threats ΓÇö national news events, political events, distant disasters ΓÇö in any meaningful way. Their world is their home, their caregivers, and their immediate environment.

Do: Limit their exposure to news coverage entirely. Maintain routine ΓÇö routine is the most powerful communicator of safety available to a child under 5.

Do say (if they ask): "Some people got hurt and the grown-ups are helping them. You are safe. I am here."

Ages 6ΓÇô10

Children this age are aware of the broader world and will hear things from peers, older siblings, and media. They need information, not protection from information.

Do say: Honest, age-appropriate explanation + your assessment of their safety + an action they can take (donate, write a card, help). Agency is one of the most powerful antidotes to fear-based trauma responses.

The One Rule That Applies to All of Them

Never punish a child for asking a hard question. A child who learns that asking hard questions results in discomfort, redirection, or anger does not learn to stop having hard thoughts. They learn to have them alone.

