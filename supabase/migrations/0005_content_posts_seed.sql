Sight words ΓÇö high-frequency words like "the," "said," "was" ΓÇö follow irregular phonics rules. For these specific words, memorization is genuinely necessary. But sight words are a supplement, not a strategy.

The correct progression:

Build phonemic awareness (hearing sounds in words orally)

Introduce systematic phonics (letter-sound relationships)

Begin blending CVC words (cat, dog, run)

Layer in sight words for the irregulars phonics cannot cover

